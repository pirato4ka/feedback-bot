def schedule_label(kind: str, interval_seconds: int | None) -> str:
    if kind == BROADCAST_MODE_PERIODIC and interval_seconds:
        return SCHEDULE_PERIODIC.format(interval=humanize_interval(interval_seconds))
    return SCHEDULE_ONCE

